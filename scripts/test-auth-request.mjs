import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
const source = stripTypeScriptTypes(readFileSync('src/lib/authRequest.ts', 'utf8'));
const { authDeadline, authBoundedFetch } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
assert.equal(await authDeadline(Promise.resolve('ok'), 20), 'ok');
await assert.rejects(authDeadline(Promise.reject(new Error('invalid login')), 20), /invalid login/);
await assert.rejects(authDeadline(new Promise(() => {}), 5), /Sign-in is taking too long/);
let calls = 0;
globalThis.fetch = async (_input, init) => { calls++; return new Response('ok'); };
assert.equal(await (await authBoundedFetch('https://example.invalid/auth/v1/token')).text(), 'ok');
const controller = new AbortController();
controller.abort(new Error('cancelled'));
globalThis.fetch = async (_input, init) => { assert.equal(init.signal.aborted, true); throw init.signal.reason; };
await assert.rejects(authBoundedFetch('https://example.invalid/auth/v1/token', { signal: controller.signal }), /cancelled/);
const uploadInit = { method: 'POST', body: 'test' };
globalThis.fetch = async (_input, init) => { assert.equal(init, uploadInit); return new Response('ok'); };
await authBoundedFetch('https://example.invalid/storage/v1/object/test', uploadInit);
console.log('6 auth request checks passed (success, error, hang, transport, cancellation, upload isolation)');
